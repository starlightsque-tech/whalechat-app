function stockRow(t, name, sector, color, exchange, provider) {
  return {
    ticker: t,
    displayTicker: t,
    finnhubSymbol: t,
    assetClass: 'us',
    name,
    exchange: exchange || 'NASDAQ',
    currency: 'USD',
    color: color || '#2ee6c9',
    sector: sector || 'Stock',
    provider,
    price: BASE[t] || 0,
    prevClose: BASE[t] || 0,
    synthetic: false,
    twentyFourSeven: false
  };
}
function cryptoRow(t, name, color, sector) {
  return {
    ticker: t,
    displayTicker: t.replace(/USDT$/, '/USDT'),
    finnhubSymbol: 'BINANCE:' + t,
    assetClass: 'crypto',
    name,
    exchange: 'Binance',
    currency: 'USDT',
    color: color || '#f3ba2f',
    sector: sector || 'Crypto',
    provider: 'binance',
    price: BASE[t] || 0,
    prevClose: BASE[t] || 0,
    synthetic: false,
    twentyFourSeven: true
  };
}

